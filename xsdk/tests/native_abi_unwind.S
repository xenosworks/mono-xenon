.macro LOAD64 reg, hi, mid, low, last
	lis \reg, \hi
	ori \reg, \reg, \mid
	sldi \reg, \reg, 32
	oris \reg, \reg, \low
	ori \reg, \reg, \last
.endm

.macro CHECK64 reg, hi, mid, low, last
	LOAD64 r0, \hi, \mid, \low, \last
	cmpd r0, \reg
	bne unwind64_fail
.endm

